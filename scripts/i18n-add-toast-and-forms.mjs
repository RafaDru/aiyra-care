function merge(locale, patch) {
  const path = join(localesDir, locale)
  const data = JSON.parse(readFileSync(path, 'utf8'))
  Object.assign(data, patch)
  if (locale === 'pt-BR.json') {
    data.common.ok = 'OK'
    data.common.error = 'Erro'
    data.common.unknownError = 'Erro desconhecido'
  } else {
    data.common.ok = 'OK'
    data.common.error = 'Error'
    data.common.unknownError = 'Unknown error'
  }
  data.patient.form = locale === 'pt-BR.json' ? patientFormPt : patientFormEn
  writeFileSync(path, JSON.stringify(data, null, 2) + '\n', 'utf8')
}

